CREATE OR REPLACE FUNCTION "public"."match_documents"("query_embedding" "public"."vector", "match_threshold" double precision, "match_count" integer) RETURNS TABLE("chunk_id" "uuid", "section" "text", "content" "text", "document_title" "text", "document_path" "text", "similarity" double precision)
    LANGUAGE "plpgsql"
    AS $$
BEGIN
  RETURN QUERY
  SELECT
   -- Explicit cast to text
    d.id AS chunk_id,
    d.section::text,
    d.content::text,
    doc.title::text AS document_title,
    doc.path::text AS document_path,
    1 - (d.embedding <=> query_embedding) AS similarity
  FROM doc_chunk d
  JOIN document doc ON d.document_id = doc.id
  -- WHERE 1 - (d.embedding <=> query_embedding) > match_threshold
  ORDER BY d.embedding <=> query_embedding ASC
  LIMIT match_count;
END;
$$;


